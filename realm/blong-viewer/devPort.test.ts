/**
 * Which UDP port this package's viewer listens on (`@@D-953`).
 *
 * The rule exists because three suites load the viewer and CI runs their packages side by side: one
 * constant meant every package bound the same socket and all but the first died with `EADDRINUSE`.
 * The property that matters is *different numbers for different packages*, which is what the first
 * case pins; the two ends — a developer's rc, and a tree with no monorepo around it — have to stay on
 * the conventional port, because both are places where the destination is written once by hand.
 *
 * The fixtures are directories rather than this repository, so the test states the rule instead of
 * whatever this checkout happens to contain.
 */

import {mkdirSync, mkdtempSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {dirname, join} from 'node:path';
import {test} from 'tap';

import {viewerUdpPort} from './devPort.ts';

/** A directory holding `files`, keyed by relative path, with their content. */
function fixture(files: Record<string, string>): string {
    const root = mkdtempSync(join(tmpdir(), 'blong-viewer-port-'));
    for (const [relative, content] of Object.entries(files)) {
        const full = join(root, relative);
        mkdirSync(dirname(full), {recursive: true});
        writeFileSync(full, content);
    }
    return root;
}

/** The `rush.json` a monorepo of `packages` has, with the comment the loader has to read past. */
const rush = (packages: string[]): string =>
    `// generated by rush\n{\n  "projects": [\n${packages
        .map(name => `    {"packageName": "${name}"}`)
        .join(',\n')}\n  ]\n}\n`;

test('each package of a monorepo derives its own port', async t => {
    const root = fixture({
        'rush.json': rush(['@demo/first', '@demo/chat', '@demo/sport']),
        'one/package.json': JSON.stringify({name: '@demo/first'}),
        'two/package.json': JSON.stringify({name: '@demo/chat'}),
        'three/package.json': JSON.stringify({name: '@demo/sport'}),
    });
    try {
        const ports = ['one', 'two', 'three'].map(dir => viewerUdpPort(join(root, dir)));
        t.same(ports, [9600, 9601, 9602], 'the port is the base plus the index in rush.json');
        t.equal(new Set(ports).size, ports.length, 'no two packages share a number');
    } finally {
        rmSync(root, {recursive: true, force: true});
    }
});

test('a developer rc keeps the conventional port', async t => {
    const root = fixture({
        'rush.json': rush(['@demo/chat']),
        'package.json': JSON.stringify({name: '@demo/chat'}),
        '.blong_devrc': 'log:\n    destination: {port: 9999}\n',
    });
    try {
        t.equal(
            viewerUdpPort(root),
            9999,
            'the rc writes the destination for every package, so the listener answers where it points',
        );
    } finally {
        rmSync(root, {recursive: true, force: true});
    }
});

test('a tree with no monorepo around it keeps the conventional port', async t => {
    const root = fixture({'package.json': JSON.stringify({name: '@demo/lonely'})});
    try {
        t.equal(viewerUdpPort(root), 9999, 'a container has no index to derive from');
    } finally {
        rmSync(root, {recursive: true, force: true});
    }
});
