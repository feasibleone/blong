import {adapter} from '@feasibleone/blong';
import type {IAgentEngineAccount, IComponentK8sContribution} from '@feasibleone/blong/types';

/**
 * `adapter/engine.ts` — this deployment's engine instance, one of the realm's accounts maps.
 *
 * The implementation is `adapter.engine` in `core/blong-gogo`, because the SDK client belongs to an
 * adapter and not to a handler (`@@D-700`). What is left here is what a deployment decides: the
 * accounts, their kinds and whichever of them a ticket may name (`@@D-708`).
 *
 * The namespace is the instance's own, and a second instance is another file with another namespace
 * and its own block — `agent.review.accounts` beside `agent.engine.accounts` (`@@D-712`).
 */
export default adapter<
    {accounts?: Record<string, IAgentEngineAccount>} & IComponentK8sContribution
>(() => ({
    extends: 'adapter.engine',
    activation: {
        default: {
            namespace: 'engine',
            accounts: {},
            // The key is read from a variable the cluster fills from a Secret, so a deployment never
            // carries one in its tree (`@@T-578`): an account names `apiKeyEnv` and this is the
            // variable it names. Here rather than under `release`, because the tree is generated by a
            // `k8s` run and that run merges no other block.
            k8sEnv: [
                {
                    name: 'AGENT_ENGINE_API_KEY',
                    valueFrom: {secretKeyRef: {name: 'blong-agent-engine', key: 'apiKey'}},
                },
            ],
            // The harness keeps its own session store, which a resume names (`@@D-711`), so it is a
            // volume of its own rather than a directory inside the workspace a ticket is jailed to.
            k8sVolumes: {
                'blong-agent-harness': {size: '1Gi', mountPath: '/home/node/.dsh'},
            },
            // A `deepseek` account runs the harness as a second process in this container, so the
            // request has to fit both (`@@T-579`).
            k8sResources: {
                requests: {cpu: '500m', memory: '1Gi'},
                limits: {cpu: '2', memory: '3Gi'},
            },
        },
        integration: {
            // Scripted accounts, so the realm's tests run the whole loop without a key or a network.
            // `local` takes three turns and two tool calls, which is what makes the checkpoint-per-step
            // and the tool boundary observable; `asking` parks on a human question.
            accounts: {
                local: {
                    kind: 'sim',
                    mode: 'step',
                    script: [
                        {toolCall: {toolName: 'listFiles', args: {}}},
                        {
                            toolCall: {
                                toolName: 'writeFile',
                                args: {path: 'NOTES.md', content: 'The workspace is ready.'},
                            },
                        },
                        {text: 'Wrote NOTES.md and said why.'},
                    ],
                },
                asking: {
                    kind: 'sim',
                    mode: 'step',
                    script: [
                        {
                            toolCall: {
                                toolName: 'askHuman',
                                args: {question: 'Which fix do you want?'},
                            },
                        },
                        {text: 'Applied the answer.'},
                    ],
                },
                // Asks a question the answer method will not answer in time, so the suspension path is
                // the real one rather than a stand-in for it.
                slow: {
                    kind: 'sim',
                    mode: 'step',
                    script: [
                        {
                            toolCall: {
                                toolName: 'askHuman',
                                args: {question: 'never: is anyone there?'},
                            },
                        },
                        {text: 'The answer arrived after all.'},
                    ],
                },
                // The engine owns the loop: one prompt in, the events it reports out.
                native: {
                    kind: 'sim',
                    mode: 'native',
                    script: [
                        {text: 'Read the workspace.'},
                        {text: 'It was already right, so nothing was written.'},
                    ],
                },
            },
        },
        // A real model on a LAN host, over Ollama's OpenAI-compatible endpoint. No extra provider
        // package is needed for that: the AI SDK's OpenAI client takes a base URL, so `vercel` is
        // enough and the account differs only in where it points (`@@T-591`).
        ollama: {
            accounts: {
                qwen: {
                    kind: 'vercel',
                    modelName: 'qwen2.5-coder:14b',
                    baseUrl: 'http://localhost:11434/v1',
                    // Ollama wants a non-empty key and ignores its value.
                    apiKey: 'ollama',
                    // A short answer keeps the turn inside a 32k context and a readable runtime.
                    maxOutputTokens: 256,
                    temperature: 0,
                },
            },
        },
    },
}));
