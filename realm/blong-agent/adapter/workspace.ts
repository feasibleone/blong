import {tmpdir} from 'node:os';
import {join} from 'node:path';

import {adapter} from '@feasibleone/blong';
import type {IComponentK8sContribution} from '@feasibleone/blong/types';

/**
 * `adapter/workspace.ts` — where this deployment's tickets keep their files.
 *
 * The implementation is `adapter.workspace` in `core/blong-gogo`; what is left here is the decision a
 * deployment makes: the root, the template a fresh workspace is copied from, and whether a command may
 * run at all (`@@D-710`). Commands are off by default — a deployment turns them on deliberately, and
 * the pod that does mounts nothing but this root.
 *
 * The shape is declared here rather than imported from the runtime, because a realm does not depend on
 * `blong-gogo`: what a port's configuration is belongs to the port, and this is the slice of it a
 * deployment writes.
 */
export interface IWorkspaceAdapterConfig {
    root?: string;
    template?: string;
    shell?: {
        enabled?: boolean;
        timeoutMs?: number;
        maxOutputBytes?: number;
        env?: Record<string, string>;
    };
}

export default adapter<IWorkspaceAdapterConfig & IComponentK8sContribution>(() => ({
    extends: 'adapter.workspace',
    activation: {
        default: {
            namespace: 'workspace',
            root: join(tmpdir(), 'blong-agent-workspace'),
            shell: {enabled: false},
            // What a deployment mounts where the root points (`@@T-578`). The `k8s` keys live in
            // `default` because the tree is generated by a `k8s` run, which merges no other block;
            // the root that names the same directory is a `release` answer, because a checkout must
            // not try to write there.
            k8sVolumes: {
                'blong-agent-workspace': {size: '10Gi', mountPath: '/srv/blong-agent'},
            },
        },
        integration: {
            // Each test run gets its own directory, so two runs never share a ticket's files.
            root: join(tmpdir(), `blong-agent-workspace-${process.pid}`),
            shell: {enabled: true, timeoutMs: 30_000},
        },
        release: {
            // The root the claim above is mounted at: a restart that threw the edits away would leave
            // a resume replaying a workspace that lost its work (`@@T-578`).
            root: '/srv/blong-agent',
        },
    },
}));
