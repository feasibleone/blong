/**
 * scripts/lib/checks.ts — what a deployed suite has to answer for, after the tree is applied.
 *
 * The asserts of the shell runbook it replaces, one function per claim, each reading the cluster back
 * rather than restating what was written. That distinction is the whole point of the file: an apply
 * that succeeded says the API accepted a document, and a deployment that works says the process
 * reached its tables, the portal serves a page, and the answer a caller gets carries no private key.
 *
 * Every failure is a `fail` and every inconclusive answer is a `warn`, in the proportions the shell
 * settled on after each of them had a false positive: a missing bundle is a warning because the
 * artifact may legitimately carry none, while a login answer with a private key in it is the one thing
 * that fails a run outright.
 */
import {existsSync} from 'node:fs';
import {spawn} from 'node:child_process';

import {serviceNames} from './artifacts.ts';
import {
    execInPod,
    getField,
    getJson,
    objectExists,
    podHasNode,
    portAnswers,
    portForward,
    readyPodName,
    type IPortForward,
} from './cluster.ts';
import {fail, waitFor, type IStepIo} from './exec.ts';
import {
    pageAnswer,
    privateKeyFields,
    tokenAnswer,
    upgradeArguments,
    validationRefusal,
} from './rules.ts';
import {servicesNamespaceOf} from './trees.ts';

/** The release step, which is a Job: a deployed process runs `release`, and the schema is beside it. */
export const migrationStepRan = async (
    {namespace, timeoutSeconds = 600}: {namespace: string; timeoutSeconds?: number},
    io: IStepIo,
): Promise<void> => {
    const listed = await io.capture('kubectl', ['-n', namespace, 'get', 'jobs', '-o', 'name'], {
        allowFailure: true,
    });
    const job = listed
        .split('\n')
        .map(line => line.trim())
        .filter(line => line.includes('migrate'))[0];
    if (!job) fail('the tree carries no migration Job, so nothing created the schema');
    // What the Job *runs* is checked as well as that it ran: a tree regenerated by hand can carry the
    // attempt an older generator wrote, and the shape that shipped once lost the deployment's config
    // because a positional followed a flag (F-414).
    const args = (
        await getField({
            namespace,
            resource: job,
            jsonPath: '{.spec.template.spec.containers[0].args[*]}',
        }, io)
    )
        .split(/\s+/)
        .filter(Boolean);
    const wrong = upgradeArguments(args);
    if (wrong) fail(wrong);
    await io.run('kubectl', [
        '-n',
        namespace,
        'wait',
        `--for=condition=complete`,
        job,
        `--timeout=${timeoutSeconds}s`,
    ]);
    io.log(`${job} completed`);
};

/**
 * No released process renders a `semlog://` reference.
 *
 * The stores behind a reference come from the merged config, and a deployment's own rc file can
 * configure them for a process whose intent says not to render one — which is how a released pod
 * printed `config: semlog://p/<id>` for a payload nobody reads from that stream (T-243). Checked on
 * every running container of the suite, because the platforms differ in which logger they pick.
 */
export const noSemlogReference = async (
    {namespace, tail = 1000}: {namespace: string; tail?: number},
    io: IStepIo,
): Promise<void> => {
    const listed = await io.capture('kubectl', ['-n', namespace, 'get', 'pods', '-o', 'name'], {
        allowFailure: true,
    });
    let references = 0;
    for (const pod of listed
        .split('\n')
        .map(line => line.trim())
        .filter(Boolean)
        .filter(line => !line.includes('/cache-'))) {
        const logs = await io.capture(
            'kubectl',
            ['-n', namespace, 'logs', pod, '--all-containers', `--tail=${tail}`],
            {allowFailure: true},
        );
        const count = logs.split('\n').filter(line => line.includes('semlog://')).length;
        if (count) {
            io.warn(`${pod} printed ${count} semlog reference(s)`);
            references += count;
        }
    }
    if (references) fail('a released process printed a semlog reference');
    io.log('no container printed a semlog reference');
};

/** Which node each pod landed on — the cheapest way to see that a two-node cluster is really two. */
export const podsOnNodesReport = async (
    {namespace}: {namespace: string},
    io: IStepIo,
): Promise<void> => {
    const listed = await io.capture('kubectl', [
        '-n',
        namespace,
        'get',
        'pods',
        '-o',
        'custom-columns=POD:.metadata.name,NODE:.spec.nodeName,STATUS:.status.phase',
    ]);
    io.log(listed.trimEnd());
};

