/**
 * The cipher behind a sealed stream route (`@@D-949`).
 *
 * MLE seals one message at a time: an ECDH key agreement, then a signature, per
 * payload. Measured on a 449-byte record that is ~1.7 ms and 3.2× the bytes, so
 * doing it per frame turns a burst of ten thousand records into half a minute of
 * CPU. A stream is a *sequence*, and the standard answer to a sequence is the one
 * TLS uses — agree a key once, then one AEAD call per record:
 *
 * - **once per stream** the two sides agree on a secret with ECDH, over the keys
 *   they already exchange for MLE. Nothing new is trusted; the same P-384 pair
 *   that decrypts a response derives this key;
 * - **once per frame** AES-256-GCM, ~5 µs for the same record, with the nonce
 *   built from the frame's sequence number so a replayed or reordered frame does
 *   not open.
 *
 * Two things make the nonce safe rather than merely convenient: the key is
 * derived with a **fresh salt per stream**, so no key is ever used twice, and the
 * nonce is `4 zero bytes ‖ seq`, which under a per-stream key cannot repeat
 * before 2^64 frames. A key that were ever shared between two streams would need
 * a per-stream random prefix instead — which is why the salt is generated by the
 * party that opens the stream and is never reused.
 *
 * `crypto.subtle` is the implementation on purpose: it is the only one available
 * in a browser *and* in Node (>=19), so the two sides run the same code rather
 * than two implementations that have to be kept in agreement by hand.
 */

/** Bytes of salt a stream's key is derived with. */
export const STREAM_SALT_BYTES = 16;

/** What the derived key is bound to, so a key cannot be reused for another purpose. */
export const STREAM_INFO = 'blong.stream.v1';

/** Bytes of the sequence number that prefixes a sealed frame. */
const SEQ_BYTES = 8;

/** The sequence number a frame carries, in clear, so the nonce can be rebuilt. */
export function seqBytes(seq: number): Uint8Array {
    const bytes = new Uint8Array(SEQ_BYTES);
    new DataView(bytes.buffer).setBigUint64(0, BigInt(seq), false);
    return bytes;
}

/** The nonce for `seq` under a key that belongs to one stream: 4 zero bytes, then the sequence. */
export function nonceOf(seq: number): Uint8Array {
    const nonce = new Uint8Array(12);
    nonce.set(seqBytes(seq), 4);
    return nonce;
}

/** A fresh salt, from the platform's own generator. */
export function newStreamSalt(): Uint8Array {
    return globalThis.crypto.getRandomValues(new Uint8Array(STREAM_SALT_BYTES));
}

/** A salt as the header value that carries it, and back. */
export function saltToHeader(salt: Uint8Array): string {
    return Buffer.from(salt).toString('base64url');
}

export function saltFromHeader(value: string): Uint8Array {
    return new Uint8Array(Buffer.from(value, 'base64url'));
}

export interface IDeriveStreamKeyOptions {
    /** This side's private encrypt key, as the JWK MLE already resolved. */
    privateJwk: Record<string, unknown> | JsonWebKey;
    /** The other side's public encrypt key. */
    peerPublicJwk: Record<string, unknown> | JsonWebKey;
    /** The salt the stream was opened with. */
    salt: Uint8Array;
    /** What the frame is for, bound into the key: the method name and envelope. */
    info?: string;
}

/**
 * The AES-GCM key two sides derive from the pair they already hold.
 *
 * Both sides compute the same secret — each multiplies its own private key by the
 * other's public one — so neither sends a key. The salt makes it a key for *this*
 * stream, and the info string keeps it from being usable anywhere else.
 */
export async function deriveStreamKey({
    privateJwk,
    peerPublicJwk,
    salt,
    info = STREAM_INFO,
}: IDeriveStreamKeyOptions): Promise<CryptoKey> {
    const curve = String(privateJwk.crv ?? 'P-384');
    const privateKey = await globalThis.crypto.subtle.importKey(
        'jwk',
        privateJwk as JsonWebKey,
        {name: 'ECDH', namedCurve: curve},
        false,
        ['deriveBits'],
    );
    const peerKey = await globalThis.crypto.subtle.importKey(
        'jwk',
        peerPublicJwk as JsonWebKey,
        {name: 'ECDH', namedCurve: String(peerPublicJwk.crv ?? curve)},
        false,
        [],
    );
    const shared = await globalThis.crypto.subtle.deriveBits(
        {name: 'ECDH', public: peerKey},
        privateKey,
        384,
    );
    const hkdf = await globalThis.crypto.subtle.importKey('raw', shared, 'HKDF', false, [
        'deriveBits',
    ]);
    const bits = await globalThis.crypto.subtle.deriveBits(
        {
            name: 'HKDF',
            hash: 'SHA-256',
            salt: salt as unknown as BufferSource,
            info: new TextEncoder().encode(info) as unknown as BufferSource,
        },
        hkdf,
        256,
    );
    return globalThis.crypto.subtle.importKey('raw', bits, {name: 'AES-GCM'}, false, [
        'encrypt',
        'decrypt',
    ]);
}

/**
 * One frame: the sequence in clear, then the sealed payload.
 *
 * The sequence is outside the ciphertext on purpose — the reader needs it to
 * build the nonce — and it is authenticated anyway, because changing it changes
 * the nonce and the tag stops verifying.
 */
export async function sealFrame(
    key: CryptoKey,
    seq: number,
    plaintext: Uint8Array,
    info: string = STREAM_INFO,
): Promise<Uint8Array> {
    const sealed = new Uint8Array(
        await globalThis.crypto.subtle.encrypt(
            {
                name: 'AES-GCM',
                iv: nonceOf(seq) as unknown as BufferSource,
                additionalData: new TextEncoder().encode(info) as unknown as BufferSource,
            },
            key,
            plaintext as unknown as BufferSource,
        ),
    );
    const frame = new Uint8Array(SEQ_BYTES + sealed.length);
    frame.set(seqBytes(seq));
    frame.set(sealed, SEQ_BYTES);
    return frame;
}

/**
 * The payload of one frame, or a failure when it is not the frame it claims.
 *
 * `seq` comes from the caller rather than from the frame: the reader counts what
 * it has opened, so a frame that arrives twice, or out of order, is refused
 * instead of quietly opening under the wrong nonce.
 */
export async function openFrame(
    key: CryptoKey,
    seq: number,
    frame: Uint8Array,
    info: string = STREAM_INFO,
): Promise<Uint8Array> {
    const claimed = Number(new DataView(frame.buffer, frame.byteOffset, SEQ_BYTES).getBigUint64(0, false));
    if (claimed !== seq) {
        throw new Error(`stream frame out of sequence: expected ${seq}, received ${claimed}`);
    }
    return new Uint8Array(
        await globalThis.crypto.subtle.decrypt(
            {
                name: 'AES-GCM',
                iv: nonceOf(seq) as unknown as BufferSource,
                additionalData: new TextEncoder().encode(info) as unknown as BufferSource,
            },
            key,
            frame.subarray(SEQ_BYTES) as unknown as BufferSource,
        ),
    );
}
